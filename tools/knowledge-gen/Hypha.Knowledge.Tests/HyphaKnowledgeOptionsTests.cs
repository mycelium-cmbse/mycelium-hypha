namespace Hypha.Knowledge.Tests
{
    using System;
    using System.IO;
    using System.Linq;
    using System.Net.Http;
    using System.Threading;
    using System.Threading.Tasks;

    using Hypha.Knowledge;
    using Hypha.Knowledge.Api;
    using Hypha.Knowledge.Generation;
    using Hypha.Knowledge.Layout;
    using Hypha.Knowledge.Releases;

    using Microsoft.Extensions.DependencyInjection;
    using Microsoft.Extensions.Logging;

    using Moq;

    /// <summary>
    /// Tests for the one place a caller can vary how fetching and generation behave.
    /// </summary>
    [TestFixture]
    public class HyphaKnowledgeOptionsTests
    {
        [Test]
        public void Every_setting_has_a_working_default()
        {
            // A caller inside the repository should be able to say AddHyphaKnowledge() and nothing else.
            var options = new HyphaKnowledgeOptions();

            Assert.Multiple(() =>
            {
                Assert.That(options.ApiBaseAddress, Is.EqualTo(Upstream.DefaultApiBaseAddress));
                Assert.That(options.RawContentBaseAddress, Is.EqualTo(Upstream.DefaultRawContentBaseAddress));
                Assert.That(options.MaxDownloadConcurrency, Is.EqualTo(6));
                Assert.That(options.Token, Is.Null);
                Assert.That(options.RepositoryRoot, Is.Null);
                Assert.That(() => options.Validate(), Throws.Nothing);
            });
        }

        [Test]
        public void A_concurrency_below_one_is_refused_at_registration()
        {
            // Caught while composing rather than on the first download, where the stack would be
            // several layers away from the setting that caused it.
            Assert.Throws<ArgumentOutOfRangeException>(
                () => new ServiceCollection().AddHyphaKnowledge(o => o.MaxDownloadConcurrency = 0));
        }

        [Test]
        public void The_options_are_resolvable_so_a_caller_can_read_what_it_composed()
        {
            using var provider = new ServiceCollection()
                .AddHyphaKnowledge(o => o.MaxDownloadConcurrency = 3)
                .BuildServiceProvider();

            Assert.That(
                provider.GetRequiredService<HyphaKnowledgeOptions>().MaxDownloadConcurrency, Is.EqualTo(3));
        }

        [Test]
        public void The_api_host_reaches_the_client_and_the_layout_reaches_the_root()
        {
            var host = new Uri("https://ghe.example.invalid/api/v3/");
            var root = new DirectoryInfo(TestContext.CurrentContext.WorkDirectory);

            using var provider = new ServiceCollection()
                .AddHyphaKnowledge(o =>
                {
                    o.ApiBaseAddress = host;
                    o.RepositoryRoot = root;
                })
                .BuildServiceProvider();

            Assert.Multiple(() =>
            {
                Assert.That(
                    provider.GetRequiredService<IHttpClientFactory>()
                        .CreateClient(ServiceCollectionExtensions.UpstreamClientName).BaseAddress,
                    Is.EqualTo(host));
                Assert.That(
                    provider.GetRequiredService<IKnowledgeLayout>().Root.FullName, Is.EqualTo(root.FullName));
            });
        }

        [Test]
        public void The_raw_content_host_reaches_the_grammar_reference()
        {
            // The one setting that shows up in generated bytes rather than in a request.
            using var provider = new ServiceCollection()
                .AddHyphaKnowledge(o => o.RawContentBaseAddress = new Uri("https://mirror.invalid/"))
                .BuildServiceProvider();

            var rendered = provider.GetRequiredService<Grammar.IGrammarReference>().RenderGraphical(
                "2026-05",
                "owner/repo",
                new Grammar.GrammarParser().ParseGraphical(GraphicalGrammarParserTests.Graphical));

            Assert.That(rendered, Does.Contain("https://mirror.invalid/owner/repo/2026-05/bnf/"));
        }

        [Test]
        public void Logging_is_available_to_every_generator()
        {
            // #77 needs somewhere for install-time progress to go; without AddLogging the generators
            // would not even resolve.
            using var provider = new ServiceCollection().AddHyphaKnowledge().BuildServiceProvider();

            Assert.Multiple(() =>
            {
                Assert.That(provider.GetService<ILoggerFactory>(), Is.Not.Null);
                Assert.That(provider.GetServices<IKnowledgeGenerator>().ToList(), Has.Count.EqualTo(5));
            });
        }

        [Test]
        public void The_pim_model_is_read_from_the_omg_document_server_by_default()
        {
            var options = new HyphaKnowledgeOptions();

            Assert.Multiple(() =>
            {
                Assert.That(options.PimAddress, Is.EqualTo(ApiUpstream.DefaultPimAddress));
                Assert.That(options.PimAddress.IsAbsoluteUri, Is.True);
                Assert.That(options.PimAddress.Scheme, Is.EqualTo(Uri.UriSchemeHttps));
                Assert.That(options.PimAddress.AbsolutePath, Does.EndWith("/" + ApiInputs.PimModel));
            });
        }

        [Test]
        public void A_missing_pim_address_is_refused_at_registration()
        {
            // Caught while composing rather than on `hypha api fetch`, several layers away.
            Assert.Multiple(() =>
            {
                Assert.Throws<ArgumentNullException>(
                    () => new HyphaKnowledgeOptions { PimAddress = null! }.Validate());
                Assert.Throws<ArgumentNullException>(
                    () => new ServiceCollection().AddHyphaKnowledge(o => o.PimAddress = null!));
            });
        }

        [Test]
        public async Task The_pim_address_reaches_the_installer()
        {
            // What lets a test serve the PIM model from a stub rather than from the document server.
            var address = new Uri("https://documents.example.invalid/pim.xmi");
            var root = Directory.CreateDirectory(
                Path.Combine(TestContext.CurrentContext.WorkDirectory, $"pim-address-{Guid.NewGuid():N}"));

            var fetcher = new Mock<IReleaseFetcher>();
            fetcher
                .Setup(mock => mock.DownloadAsync(
                    It.IsAny<string>(), It.IsAny<string>(), It.IsAny<string>(), It.IsAny<FileInfo>(),
                    It.IsAny<bool>(), It.IsAny<CancellationToken>()))
                .ReturnsAsync((string _, string _, string _, FileInfo destination, bool _, CancellationToken _) =>
                    destination);

            var documents = new Mock<IDocumentDownloader>();
            documents
                .Setup(mock => mock.DownloadAsync(
                    It.IsAny<Uri>(), It.IsAny<FileInfo>(), It.IsAny<bool>(), It.IsAny<CancellationToken>()))
                .ReturnsAsync((Uri _, FileInfo destination, bool _, CancellationToken _) => destination);

            var resolver = new Mock<ICommitResolver>();
            resolver
                .Setup(mock => mock.ResolveAsync(It.IsAny<string>(), It.IsAny<string>(), It.IsAny<CancellationToken>()))
                .ReturnsAsync("abc123");

            try
            {
                // Registered after the library's own, so these are the ones the installer is given.
                using var provider = new ServiceCollection()
                    .AddHyphaKnowledge(o =>
                    {
                        o.PimAddress = address;
                        o.RepositoryRoot = root;
                    })
                    .AddSingleton(fetcher.Object)
                    .AddSingleton(documents.Object)
                    .AddSingleton(resolver.Object)
                    .BuildServiceProvider();

                await provider.GetRequiredService<IApiInstaller>()
                    .InstallAsync(new ApiInstallRequest { Tag = "2026-04" });

                documents.Verify(
                    mock => mock.DownloadAsync(
                        address, It.IsAny<FileInfo>(), It.IsAny<bool>(), It.IsAny<CancellationToken>()),
                    Times.Once);

                Assert.That(
                    provider.GetRequiredService<IApiLayout>().InstalledTags, Is.EqualTo(new[] { "2026-04" }));
            }
            finally
            {
                root.Refresh();
                if (root.Exists)
                {
                    root.Delete(recursive: true);
                }
            }
        }
    }
}
