namespace Hypha.Knowledge.Query
{
    using System;
    using System.Collections.Concurrent;
    using System.IO;
    using System.Text;
    using System.Text.Json;
    using System.Text.Json.Serialization.Metadata;

    using Hypha.Knowledge.Lookup;

    /// <summary>
    /// Generated documents read once and kept, keyed by path, until the file on disk changes.
    /// </summary>
    /// <remarks>
    /// Each read compares the file's size and last write time with the copy held, so a release
    /// regenerated by another process (the CLI, a second server) is read again on the next query
    /// rather than answered from stale memory. Two threads that miss at once may both read the file;
    /// the result is the same, so that costs time, not correctness.
    /// <para>
    /// Every way a document can fail to read ends in a <see cref="KnowledgeLookupException"/>, the one
    /// failure the query API documents: a file that is missing, too large, being rewritten, empty, not
    /// JSON, or JSON of the wrong shape.
    /// </para>
    /// </remarks>
    internal sealed class DocumentCache
    {
        /// <summary>The largest generated document read, the same bound the lookup applies.</summary>
        private const long MaxFileBytes = KnowledgeLookup.MaxFileBytes;

        /// <summary>The documents held, by full path.</summary>
        private readonly ConcurrentDictionary<string, Entry> entries = new(StringComparer.Ordinal);

        /// <summary>Returns the document at a path, reading it when it is not held or has changed.</summary>
        /// <typeparam name="T">The document's type.</typeparam>
        /// <param name="file">The generated file.</param>
        /// <param name="contract">The contract to read it through.</param>
        /// <param name="isWhole">
        /// Whether a document that read without error has every top-level member the queries rely on.
        /// </param>
        /// <param name="missing">The message for a file that does not exist.</param>
        /// <param name="regenerate">The command that regenerates the file, for the messages.</param>
        /// <returns>The document.</returns>
        /// <exception cref="KnowledgeLookupException">
        /// The file does not exist, is too large, cannot be read, is empty, or is not a valid document of
        /// its kind.
        /// </exception>
        public T Get<T>(FileInfo file, JsonTypeInfo<T> contract, Func<T, bool> isWhole, string missing, string regenerate)
            where T : class
        {
            file.Refresh();

            if (!file.Exists)
            {
                throw new KnowledgeLookupException(missing);
            }

            if (file.Length > MaxFileBytes)
            {
                throw new KnowledgeLookupException(
                    $"{file.FullName} is larger than {MaxFileBytes / (1024 * 1024)} MiB; it is not a generated document.");
            }

            var stamp = (file.Length, file.LastWriteTimeUtc);

            if (this.entries.TryGetValue(file.FullName, out var held) && held.Stamp == stamp && held.Value is T value)
            {
                return value;
            }

            var document = Parse(file, Read(file), contract, regenerate);

            if (!isWhole(document))
            {
                throw new KnowledgeLookupException(
                    $"{file.FullName} is not a complete generated document. Regenerate it with '{regenerate}'.");
            }

            this.entries[file.FullName] = new Entry(stamp, document);

            return document;
        }

        /// <summary>Reads a generated file as UTF-8 text.</summary>
        /// <param name="file">The file.</param>
        /// <returns>The file's text.</returns>
        /// <exception cref="KnowledgeLookupException">The file cannot be read.</exception>
        private static string Read(FileInfo file)
        {
            try
            {
                return File.ReadAllText(file.FullName, Encoding.UTF8);
            }
            catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
            {
                // Most likely 'hypha generate' rewriting the file at this moment, or removing it.
                throw new KnowledgeLookupException(
                    $"{file.FullName} could not be read: {exception.Message} "
                    + "If 'hypha generate' is running, try again once it has finished.",
                    exception);
            }
        }

        /// <summary>Parses a generated document's text.</summary>
        /// <typeparam name="T">The document's type.</typeparam>
        /// <param name="file">The file the text was read from, for the messages.</param>
        /// <param name="text">The text.</param>
        /// <param name="contract">The contract to read it through.</param>
        /// <param name="regenerate">The command that regenerates the file, for the messages.</param>
        /// <returns>The document.</returns>
        /// <exception cref="KnowledgeLookupException">The text is empty or not a valid document of its kind.</exception>
        private static T Parse<T>(FileInfo file, string text, JsonTypeInfo<T> contract, string regenerate)
            where T : class
        {
            T? document;

            try
            {
                document = string.IsNullOrWhiteSpace(text) ? null : JsonSerializer.Deserialize(text, contract);
            }
            catch (JsonException exception)
            {
                throw new KnowledgeLookupException(
                    $"{file.FullName} is not a valid generated document: {exception.Message} "
                    + $"Regenerate it with '{regenerate}'.",
                    exception);
            }

            return document
                   ?? throw new KnowledgeLookupException($"{file.FullName} is empty. Regenerate it with '{regenerate}'.");
        }

        /// <summary>One document held, with the size and write time of the file it was read from.</summary>
        /// <param name="Stamp">The file's size and last write time when it was read.</param>
        /// <param name="Value">The document.</param>
        private sealed record Entry((long Length, DateTime LastWriteTimeUtc) Stamp, object Value);
    }
}
